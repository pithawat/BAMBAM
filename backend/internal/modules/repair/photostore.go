// PhotoStore keeps photo files (D-022). Phase 1: LocalPhotoStore; object storage can
// replace it later without API changes.
type PhotoStore interface {
	Put(ctx context.Context, key string, data []byte) error
	Open(ctx context.Context, key string) (io.ReadCloser, error)
	Delete(ctx context.Context, key string) error
}

// LocalPhotoStore stores files under a directory (PHOTO_STORAGE_DIR). Keys are generated
// by the service ("2026/10/<uuid>.jpg") and never come from the client.
type LocalPhotoStore struct {
	root string
}

func NewLocalPhotoStore(dir string) (*LocalPhotoStore, error) {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return nil, fmt.Errorf("photo storage dir: %w", err)
	}
	if err := os.MkdirAll(abs, 0o750); err != nil {
		return nil, fmt.Errorf("create photo storage dir: %w", err)
	}
	return &LocalPhotoStore{root: abs}, nil
}

func (s *LocalPhotoStore) path(key string) (string, error) {
	p := filepath.Join(s.root, filepath.FromSlash(key))
	if !strings.HasPrefix(p, s.root+string(filepath.Separator)) {
		return "", fmt.Errorf("photo key outside storage dir: %q", key)
	}
	return p, nil
}

func (s *LocalPhotoStore) Put(_ context.Context, key string, data []byte) error {
	p, err := s.path(key)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		return err
	}
	return os.WriteFile(p, data, 0o600)
}

func (s *LocalPhotoStore) Open(_ context.Context, key string) (io.ReadCloser, error) {
	p, err := s.path(key)
	if err != nil {
		return nil, err
	}
	return os.Open(p) // #nosec G304 -- key is generated by the service and checked to stay under root
}

func (s *LocalPhotoStore) Delete(_ context.Context, key string) error {
	p, err := s.path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(p); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}

const (
	// MaxPhotoBytes is the upload limit per file (D-022).
	MaxPhotoBytes = 10 << 20
	// maxPhotoPixels guards against decompression bombs (≈ 50 MP).
	maxPhotoPixels = 50_000_000
	thumbLongEdge  = 480
	thumbQuality   = 80
)

var photoExt = map[string]string{
	"image/jpeg": ".jpg",
	"image/png":  ".png",
	"image/webp": ".webp",
	"image/heic": ".heic",
}

// detectImageType sniffs the bytes (the client's Content-Type is not trusted) and returns
// one of the allowed types from 04-api-contract.md #3, or "".
func detectImageType(data []byte) string {
	if isHEIC(data) {
		return "image/heic"
	}
	ct := http.DetectContentType(data)
	if _, ok := photoExt[ct]; ok {
		return ct
	}
	return ""
}

func isHEIC(data []byte) bool {
	if len(data) < 12 || string(data[4:8]) != "ftyp" {
		return false
	}
	switch string(data[8:12]) {
	case "heic", "heix", "hevc", "hevx", "heim", "heis", "mif1", "msf1":
		return true
	}
	return false
}

// makeThumbnail returns a JPEG with the long edge at most thumbLongEdge. HEIC cannot be
// decoded in Go: ok=false means "serve the original as the thumbnail".
func makeThumbnail(data []byte, contentType string) (thumb []byte, ok bool, err error) {
	if contentType == "image/heic" {
		return nil, false, nil
	}
	cfg, _, err := image.DecodeConfig(bytes.NewReader(data))
	if err != nil {
		return nil, false, ErrPhotoTypeNotAllowed
	}
	if cfg.Width <= 0 || cfg.Height <= 0 || cfg.Width*cfg.Height > maxPhotoPixels {
		return nil, false, ErrPhotoTooLarge
	}
	src, _, err := image.Decode(bytes.NewReader(data))
	if err != nil {
		return nil, false, ErrPhotoTypeNotAllowed
	}
	w, h := cfg.Width, cfg.Height
	if w > thumbLongEdge || h > thumbLongEdge {
		if w >= h {
			w, h = thumbLongEdge, max(1, h*thumbLongEdge/cfg.Width)
		} else {
			w, h = max(1, w*thumbLongEdge/cfg.Height), thumbLongEdge
		}
	}
	dst := image.NewRGBA(image.Rect(0, 0, w, h))
	draw.Draw(dst, dst.Bounds(), image.White, image.Point{}, draw.Src) // transparent PNG → white
	draw.BiLinear.Scale(dst, dst.Bounds(), src, src.Bounds(), draw.Over, nil)
	var buf bytes.Buffer
	if err := jpeg.Encode(&buf, dst, &jpeg.Options{Quality: thumbQuality}); err != nil {
		return nil, false, fmt.Errorf("encode thumbnail: %w", err)
	}
	return buf.Bytes(), true, nil
}
