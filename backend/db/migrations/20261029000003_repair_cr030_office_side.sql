CREATE TEMP TABLE cr030_free ON COMMIT DROP AS
SELECT b.id FROM platform.buildings b
WHERE b.id::text LIKE 'c030b1d0-%'
    AND NOT EXISTS (SELECT 1 FROM repair.tickets t WHERE t.building_id = b.id)
    AND NOT EXISTS (SELECT 1 FROM platform.assets a JOIN platform.rooms ar ON ar.id = a.room_id
                    JOIN platform.floors af ON af.id = ar.floor_id WHERE af.building_id = b.id);
DELETE FROM platform.rooms r USING platform.floors f
WHERE r.floor_id = f.id AND f.building_id IN (SELECT id FROM cr030_free);
DELETE FROM platform.floor_plans fp USING platform.floors f
WHERE fp.floor_id = f.id AND f.building_id IN (SELECT id FROM cr030_free);
DELETE FROM platform.floors f WHERE f.building_id IN (SELECT id FROM cr030_free);
DELETE FROM platform.buildings b WHERE b.id IN (SELECT id FROM cr030_free);
UPDATE platform.buildings SET model_key = NULL WHERE id::text LIKE 'c030b1d0-%';
